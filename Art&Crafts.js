let currentQuestion = 0;
let quizScore = 0;

const questionElement = document.getElementById("question");
const answersContainer = document.querySelector(".answers");
const resultElement = document.getElementById("result");

function loadQuiz() {

    const current = quizQuestions[currentQuestion];

    questionElement.textContent =
        `${currentQuestion + 1}. ${current.question}`;

    resultElement.textContent = "";

    answersContainer.innerHTML = "";

    current.options.forEach((option, index) => {

        const button = document.createElement("button");

        button.textContent = option;

        button.onclick = () => checkAnswer(index);

        answersContainer.appendChild(button);
    });
}

function checkAnswer(selectedAnswer) {

    const current = quizQuestions[currentQuestion];

    const buttons =
        answersContainer.querySelectorAll("button");

    buttons.forEach(button => {
        button.disabled = true;
    });

    if (selectedAnswer === current.answer) {

        quizScore++;

        resultElement.textContent =
            "🎉 Correct! +100 Culture Points";

    } else {

        resultElement.textContent =
            `❌ Wrong! Correct answer: ${current.options[current.answer]}`;
    }

    setTimeout(() => {

        currentQuestion++;

        if (currentQuestion < quizQuestions.length) {

            loadQuiz();

        } else {

            showQuizResult();
        }

    }, 1200);
}

function showQuizResult() {

    questionElement.textContent =
        "🎉 Craft Quiz Completed!";

    answersContainer.innerHTML = "";

    resultElement.textContent =
        `You scored ${quizScore} out of ${quizQuestions.length}!`;

    const restartButton =
        document.createElement("button");

    restartButton.textContent =
        "🔄 Play Again";

    restartButton.onclick =
        restartQuiz;

    answersContainer.appendChild(restartButton);
}

function restartQuiz() {

    currentQuestion = 0;

    quizScore = 0;

    loadQuiz();
}

loadQuiz();


