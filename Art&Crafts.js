const canvas =
    document.getElementById("artCanvas");

const ctx =
    canvas.getContext("2d");


function drawCircle() {

    ctx.beginPath();

    ctx.arc(350,175,70,0,Math.PI*2);

    ctx.stroke();

}


function drawSquare() {

    ctx.strokeRect(
        280,
        105,
        140,
        140
    );

}


function drawLine() {

    ctx.beginPath();

    ctx.moveTo(100,175);

    ctx.lineTo(600,175);

    ctx.stroke();

}


function clearCanvas() {

    ctx.clearRect(
        0,
        0,
        canvas.width,
        canvas.height
    );

}