function showCraft(name, button) {

    const craft = crafts[name];

    document.getElementById("craftTitle").textContent =
        craft.title;

    document.getElementById("craftEmoji").innerHTML = `
    <img
        src="${craft.image}"
        alt="${craft.title}"
    >
`;

    document.getElementById("craftDescription").textContent =
        craft.description;

    document.getElementById("craftRegion").textContent =
        craft.region;

    document.getElementById("craftStyle").textContent =
        craft.style;

    document.getElementById("craftMaterial").textContent =
        craft.material;

    document.getElementById("craftTheme").textContent =
        craft.theme;


    document.querySelectorAll(".craft-card")
        .forEach(card => {
            card.classList.remove("active");
        });

    button.classList.add("active");
}


