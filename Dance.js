let currentQuestion = 0;

let quizScore = 0;


function loadQuiz() {

    const q = quizQuestions[currentQuestion];

    document.getElementById("quizNumber").innerText =
        `Question ${currentQuestion + 1} / ${quizQuestions.length}`;

    document.getElementById("quizQuestion").innerText =
        q.question;

    const buttons =
        document.querySelectorAll(".options button");

    buttons.forEach((button, index) => {

        button.innerText =
            q.options[index];

        button.disabled = false;

    });

    document.getElementById("quizResult").innerText =
        "";

}


function checkAnswer(selected) {

    const question =
        quizQuestions[currentQuestion];

    const result =
        document.getElementById("quizResult");

    const buttons =
        document.querySelectorAll(".options button");


    buttons.forEach(button => {
        button.disabled = true;
    });


    if (selected === question.answer) {

        quizScore += 100;

        result.innerText =
            "✅ Correct! +100 Dance Points";

        result.style.color =
            "#236b55";

    } else {

        result.innerText =
            `❌ Incorrect! Correct answer: ${question.options[question.answer]}`;

        result.style.color =
            "#c0392b";

    }


    document.getElementById("score").innerText =
        quizScore;


    setTimeout(() => {

        currentQuestion++;

        if (currentQuestion < quizQuestions.length) {

            loadQuiz();

        } else {

            document.getElementById("quizQuestion").innerText =
                `🎉 Quiz Completed! You earned ${quizScore} points.`;

            document.getElementById("quizNumber").innerText =
                "Completed";

            document.querySelector(".options").innerHTML = `
                <button onclick="restartQuiz()">
                    🔄 Play Again
                </button>
            `;

        }

    }, 1300);

}


function restartQuiz() {

    currentQuestion = 0;

    quizScore = 0;

    document.getElementById("score").innerText =
        "0";

    document.querySelector(".options").innerHTML = `

        <button onclick="checkAnswer(0)"></button>

        <button onclick="checkAnswer(1)"></button>

        <button onclick="checkAnswer(2)"></button>

        <button onclick="checkAnswer(3)"></button>

    `;

    loadQuiz();

}


