/* =========================================
   DANCE STEPS GAME
========================================= */

let stepSequence = [];

const correctSequence = [
    "LEFT",
    "RIGHT",
    "CLAP"
];


function danceStep(step) {

    stepSequence.push(step);

    document.getElementById("stepDisplay").innerText =
        step;

    if (stepSequence.length === correctSequence.length) {

        if (
            stepSequence.join(",") ===
            correctSequence.join(",")
        ) {

            document.getElementById("stepMessage").innerText =
                "🎉 Perfect! You completed the rhythm!";

        } else {

            document.getElementById("stepMessage").innerText =
                "❌ Try again. Follow LEFT → RIGHT → CLAP";

        }

    }

}


function resetSteps() {

    stepSequence = [];

    document.getElementById("stepDisplay").innerText =
        "Ready?";

    document.getElementById("stepMessage").innerText =
        "Start your rhythm!";

}


